import numpy as np
from scipy.spatial.transform import Rotation

QX1, QY1, QZ1, QW1 = 0.0040894690685501483, 0.033268146939290207, -0.0041170368480269665, 0.99942961565562749
TX1, TY1, TZ1 = 2.8802772563599532, -1.5993679228663134, 1.6974696095332318

QX2, QY2, QZ2, QW2 = -0.0063965740291415663, 0.42511457534317137, 0.29719871309628554, 0.85493251581946328
TX2, TY2, TZ2 = -3.909763822334499, -1.7659625139957409, 1.9244647468860177

R1 = Rotation.from_quat([QX1, QY1, QZ1, QW1]).as_matrix()
R2 = Rotation.from_quat([QX2, QY2, QZ2, QW2]).as_matrix()

T1 = np.array([[TX1], [TY1], [TZ1]])
T2 = np.array([[TX2], [TY2], [TZ2]])

C1 = -R1.T @ T1
C2 = -R2.T @ T2

R12 = R2 @ R1.T

T12 = C2 - C1

print(R12 @ np.array([0,0,-1]))

print(R12, T12)